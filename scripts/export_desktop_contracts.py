def expected_outputs() -> dict[Path, str]:
    schema = build_schema()
    schema_text = _canonical_json(schema)
    digest = hashlib.sha256(schema_text.encode("utf-8")).hexdigest()
    manifest = {
        "schema_version": "DesktopContractManifest.v1",
        "contract_version": "1.0.0",
        "schema_sha256": digest,
        "source": "sora_sandbox.desktop_contracts.DesktopContractBundle",
        "generated_files": [
            str(SCHEMA_PATH.relative_to(ROOT)).replace("\\", "/"),
            str(TYPESCRIPT_PATH.relative_to(ROOT)).replace("\\", "/"),
        ],
        "golden_payloads": sorted(
            str(path.relative_to(ROOT)).replace("\\", "/")
            for path in build_golden()
        ),
    }
    return {
        SCHEMA_PATH: schema_text,
        MANIFEST_PATH: _canonical_json(manifest),
        TYPESCRIPT_PATH: build_typescript(schema, digest),
        **build_golden(),
    }


def write_outputs(outputs: dict[Path, str]) -> None:
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def check_outputs(outputs: dict[Path, str]) -> list[str]:
    drift: list[str] = []
    for path, expected in outputs.items():
        if not path.exists():
            drift.append(f"missing: {path.relative_to(ROOT)}")
            continue
        actual = path.read_text(encoding="utf-8")
        if actual != expected:
            drift.append(f"drift: {path.relative_to(ROOT)}")
    return drift


def main() -> int:
    parser = argparse.ArgumentParser(description="Export Desktop Shell contracts")
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail when checked-in artifacts differ from the Pydantic source",
    )
    args = parser.parse_args()
    outputs = expected_outputs()
    if args.check:
        drift = check_outputs(outputs)
        if drift:
            print("desktop contract drift detected:", file=sys.stderr)
            for item in drift:
                print(f"  - {item}", file=sys.stderr)
            return 1
        print("desktop contracts are in sync")
        return 0
    write_outputs(outputs)
    print(f"wrote {len(outputs)} desktop contract artifacts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
