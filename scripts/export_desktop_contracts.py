def _canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def build_schema() -> dict[str, Any]:
    schema = DesktopContractBundle.model_json_schema(
        by_alias=True,
        ref_template="#/$defs/{model}",
    )
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["$id"] = "https://project-sora.local/contracts/desktop/v1"
    schema["x-sora-contract-version"] = "1.0.0"
    return schema


def _ts_identifier(value: str) -> str:
    normalized = re.sub(r"[^A-Za-z0-9_$]", "_", value)
    if not normalized or normalized[0].isdigit():
        normalized = f"_{normalized}"
    return normalized


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return _ts_identifier(str(schema["$ref"]).rsplit("/", 1)[-1])
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    for union_key in ("anyOf", "oneOf"):
        if union_key in schema:
            return " | ".join(_ts_type(item) for item in schema[union_key])
    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(_ts_type({"type": item}) for item in schema_type)
    if schema_type == "string":
        return "string"
    if schema_type in {"integer", "number"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        item_type = _ts_type(schema.get("items", {}))
        return f"ReadonlyArray<{item_type}>"
    if schema_type == "object" or "properties" in schema or "additionalProperties" in schema:
        properties = schema.get("properties", {})
        if properties:
            required = set(schema.get("required", []))
            fields = []
            for name, field_schema in properties.items():
                optional = "" if name in required else "?"
                fields.append(
                    f"readonly {json.dumps(name)}{optional}: {_ts_type(field_schema)};"
                )
            return "{ " + " ".join(fields) + " }"
        additional = schema.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Readonly<Record<string, {_ts_type(additional)}>>"
        return "Readonly<Record<string, unknown>>"
    return "unknown"


def build_typescript(schema: dict[str, Any], digest: str) -> str:
    lines = [
        "/* eslint-disable */",
        "// Generated by scripts/export_desktop_contracts.py. Do not edit by hand.",
        f"export const DESKTOP_CONTRACT_SCHEMA_SHA256 = {json.dumps(digest)} as const;",
        "",
    ]
    definitions = schema.get("$defs", {})
    for name in sorted(definitions):
        definition = definitions[name]
        identifier = _ts_identifier(name)
        if definition.get("type") == "object" and definition.get("properties"):
            required = set(definition.get("required", []))
            lines.append(f"export interface {identifier} {{")
            for field_name, field_schema in definition["properties"].items():
                optional = "" if field_name in required else "?"
                lines.append(
                    f"  readonly {json.dumps(field_name)}{optional}: {_ts_type(field_schema)};"
                )
            lines.append("}")
        else:
            lines.append(f"export type {identifier} = {_ts_type(definition)};")
        lines.append("")
    lines.append(f"export type DesktopContractBundleRoot = {_ts_type(schema)};")
    lines.append("")
    return "\n".join(lines)


